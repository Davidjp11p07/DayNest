-- Fotos propias por inmueble y reseñas vinculadas a estadias finalizadas.
BEGIN;
CREATE TABLE IF NOT EXISTS inmueble_foto (
 id_foto bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_inmueble bigint NOT NULL REFERENCES inmuebles(id_i) ON DELETE CASCADE,
 tipo varchar(10) NOT NULL CHECK (tipo IN ('INTERIOR','EXTERIOR')),
 mime varchar(10) NOT NULL CHECK (mime IN ('image/jpeg','image/png')),
 descripcion varchar(160) NOT NULL DEFAULT '',
 datos bytea NOT NULL CHECK (octet_length(datos) BETWEEN 1 AND 5242880),
 creada_en timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS calificacion_reserva (
 id_calificacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_ocupacion bigint NOT NULL REFERENCES renta(id_ocupacion) ON DELETE CASCADE,
 rol_autor varchar(12) NOT NULL CHECK (rol_autor IN ('CLIENTE','PROPIETARIO')),
 puntuacion smallint NOT NULL CHECK (puntuacion BETWEEN 1 AND 5),
 comentario varchar(1000) NOT NULL DEFAULT '',
 creada_en timestamptz NOT NULL DEFAULT now(),
 UNIQUE(id_ocupacion,rol_autor)
);
COMMIT;
